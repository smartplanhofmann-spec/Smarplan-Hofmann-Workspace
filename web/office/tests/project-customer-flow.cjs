/* Actual browser forms and HTTP; no token injection or pre-created customer. */
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
async function projectCustomerFlow({page,context,navigate,ready,fixture,screenshots}) {
  const records=[],projectReads=[],capabilityReads=[];
  let lostProjectResponse=false,retryEvidence;
  const pattern='**/api/v1/**';
  await context.route(pattern,async route=>{
    const request=route.request();
    const pathname=new URL(request.url()).pathname;
    if(request.method()==='GET'&&['/api/v1/projects','/api/v1/business/capabilities'].includes(pathname)){
      const response=await route.fetch({maxRedirects:0}),value=await response.json();
      assert.equal(response.status(),200);
      if(pathname==='/api/v1/projects')projectReads.push({value});
      else capabilityReads.push(value.features);
      return route.fulfill({response});
    }
    if(request.method()!=='POST')return route.fallback();
    const response=await route.fetch({maxRedirects:0});
    const value=await response.json();
    const body=request.postDataJSON();
    const record={path:pathname,body,rawBody:request.postData(),status:response.status(),value};
    if(!request.url().includes('/login'))records.push(record);
    if(pathname==='/api/v1/projects'&&body.name==='Projektfluss Folgevorhaben'&&!lostProjectResponse){
      assert.equal(response.status(),201,'lose only a real successful server acceptance');
      assert.match(value.id,/^[a-f0-9]{32}$/);
      lostProjectResponse=true;record.delivery='aborted_after_server_acceptance';
      return route.abort('failed');
    }
    await route.fulfill({response});
  });
  const modal=()=>page.getByRole('dialog');
  try {
    await navigate(page,'Kontakte');
    await page.getByRole('button',{name:'Kontakt anlegen',exact:true}).click();
    await modal().getByLabel('Name / Firma',{exact:true}).fill('Projektfluss Kundin');
    await modal().getByLabel('E-Mail',{exact:true}).fill('projektfluss@example.test');
    await modal().getByLabel('Adresse',{exact:true}).fill('Prüfstraße 8, 10115 Berlin');
    await modal().getByRole('button',{name:'Rechnungsadresse hinzufügen',exact:true}).click();
    await modal().getByLabel('Straße / Hausnummer',{exact:true}).fill('Prüfstraße 8');
    await modal().getByLabel('Postleitzahl',{exact:true}).fill('10115');
    await modal().getByLabel('Ort',{exact:true}).fill('Berlin');
    await modal().getByRole('button',{name:'Speichern',exact:true}).click();
    await modal().waitFor({state:'detached'});await ready(page);
    const customer=records.find(r=>r.path==='/api/v1/business/contacts').value;
    assert.equal(customer.addresses[0].street,'Prüfstraße 8');
    const card=page.locator('.list-row').filter({hasText:'Projektfluss Kundin'});
    await card.getByRole('button',{name:'Bearbeiten',exact:true}).click();
    assert.equal(await modal().getByLabel('Straße / Hausnummer',{exact:true}).inputValue(),'Prüfstraße 8');
    await modal().getByLabel('Telefon',{exact:true}).fill('+49 30 123456');
    await modal().getByRole('button',{name:'Rechnungsadresse hinzufügen',exact:true}).click();
    const delivery=modal().locator('fieldset').nth(1);
    await delivery.getByLabel('Adresszweck',{exact:true}).selectOption('delivery');
    await delivery.getByLabel('Straße / Hausnummer',{exact:true}).fill('Lieferstraße 20');
    await delivery.getByLabel('Postleitzahl',{exact:true}).fill('10117');
    await delivery.getByLabel('Ort',{exact:true}).fill('Berlin');
    await modal().getByRole('button',{name:'Speichern',exact:true}).click();
    await modal().waitFor({state:'detached'});await ready(page);
    const edited=records.find(r=>r.path==='/api/v1/business/contacts/'+customer.id).value;
    assert.deepEqual(edited.addresses[0],customer.addresses[0]);
    assert.equal(edited.addresses[1].purpose,'delivery');
    await card.getByRole('button',{name:'Projekt anlegen',exact:true}).click();
    assert.equal(await modal().getByLabel('Kunde auswählen',{exact:true}).inputValue(),customer.id);
    assert.equal(await modal().getByLabel('Neuer Kunde / Auftraggeber',{exact:true}).isVisible(),false);
    await modal().getByLabel('Projektname',{exact:true}).fill('Projektfluss Vorhaben');
    await modal().getByRole('button',{name:'Projekt anlegen',exact:true}).click();
    await modal().waitFor({state:'detached'});await ready(page);
    const project=records.find(r=>r.path==='/api/v1/projects');
    assert.equal(project.body.customer_id,customer.id);assert.equal(project.body.customer,undefined);
    await page.getByRole('tab',{name:'Dokumente',exact:true}).click();await ready(page);
    await page.getByRole('button',{name:'Belegentwurf erstellen',exact:true}).click();
    await modal().getByLabel('Titel',{exact:true}).fill('Projektfluss Angebot');
    await modal().getByLabel('Beschreibung',{exact:true}).fill('Projektleistung');
    await modal().getByLabel('Menge',{exact:true}).fill('2');
    await modal().getByLabel('Einheit',{exact:true}).fill('HUR');
    await modal().getByLabel('Netto / Einheit',{exact:true}).fill('50');
    await modal().getByRole('button',{name:'Entwurf speichern',exact:true}).click();
    await modal().waitFor({state:'detached'});await ready(page);
    const offer=records.find(r=>r.path==='/api/v1/business/documents').value;
    assert.equal(offer.customer_id,customer.id);assert.equal(offer.project_id,project.value.id);
    assert.equal(offer.buyer.address_line,'Prüfstraße 8');assert.equal(offer.buyer.postal_code,'10115');assert.equal(offer.buyer.city,'Berlin');assert.equal(offer.buyer.country,'DE');
    await page.locator('.list-row').filter({hasText:'Projektfluss Angebot'}).getByRole('button',{name:'Öffnen',exact:true}).click();
    await modal().getByRole('button',{name:'→ Auftragsbestätigung',exact:true}).click();
    await modal().getByRole('heading',{name:'Auftragsbestätigung',exact:true}).waitFor();
    await modal().getByRole('button',{name:'→ Rechnung',exact:true}).click();
    await modal().getByRole('heading',{name:'Rechnung',exact:true}).waitFor();
    const recipient=modal().locator('.panel').filter({has:page.getByRole('heading',{name:'Empfänger',exact:true})});
    assert.equal(await recipient.locator('p').innerText(),'Prüfstraße 8\n10115 Berlin\nDE');
    const conversions=records.filter(r=>r.path.endsWith('/convert'));
    assert.equal(conversions.length,2);
    const invoice=conversions[1].value;
    assert.equal(invoice.status,'draft');assert.equal(invoice.customer_id,customer.id);assert.equal(invoice.project_id,project.value.id);
    assert.deepEqual(invoice.buyer,offer.buyer);assert.deepEqual(invoice.positions,offer.positions);assert.equal(invoice.totals.gross,'119.00');
    await page.screenshot({path:path.join(screenshots,'project-customer-invoice-draft-desktop.png'),fullPage:true,animations:'disabled'});
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.screenshot({path:path.join(screenshots,'project-customer-invoice-draft-mobile.png'),fullPage:true,animations:'disabled'});
    await modal().getByRole('button',{name:'Dialog schließen',exact:true}).click();
    await page.setViewportSize({width:1440,height:1000});
    await navigate(page,'Projekte');
    await page.getByRole('button',{name:'Alle Projekte',exact:true}).click();await ready(page);
    await page.getByRole('button',{name:'Neues Projekt',exact:true}).click();
    await modal().getByRole('heading',{name:'Neues Projekt',exact:true}).waitFor();
    assert.equal(await modal().getByLabel('Neuer Kunde / Auftraggeber',{exact:true}).isVisible(),true);
    await modal().getByLabel('Kunde auswählen',{exact:true}).selectOption(customer.id);
    assert.equal(await modal().getByLabel('Neuer Kunde / Auftraggeber',{exact:true}).isVisible(),false);
    await modal().getByLabel('Projektname',{exact:true}).fill('Projektfluss Folgevorhaben');
    await modal().getByRole('button',{name:'Projekt anlegen',exact:true}).click();
    await modal().getByRole('alert').waitFor();
    assert.match(await modal().getByRole('alert').innerText(),/Keine sichere Antwort erhalten/);
    assert.equal(lostProjectResponse,true);
    await page.getByRole('button',{name:'1 Antwort offen',exact:true}).waitFor();
    await page.screenshot({path:path.join(screenshots,'project-create-lost-response.png'),fullPage:true,animations:'disabled'});
    await modal().getByRole('button',{name:'Dialog schließen',exact:true}).click();
    const readsBeforeRefresh=projectReads.length;
    await navigate(page,'Projekte');
    assert.ok(projectReads.length>readsBeforeRefresh,'refresh must read the actual accepted project before retry');
    const customerProjects=read=>(Array.isArray(read.value)?read.value:read.value.items).filter(item=>item.customer_id===customer.id);
    const beforeRetry=customerProjects(projectReads.at(-1));
    assert.equal(beforeRetry.length,2,'lost response has already created the second project');
    assert.deepEqual(beforeRetry.map(item=>item.name).sort(),['Projektfluss Folgevorhaben','Projektfluss Vorhaben']);
    assert.ok(capabilityReads.some(features=>features.includes('project_creation_receipts')));
    await page.getByRole('button',{name:'1 Antwort offen',exact:true}).click();
    await modal().getByRole('heading',{name:'Unbestätigte Antworten',exact:true}).waitFor();
    const readsBeforeRetry=projectReads.length;
    await modal().getByRole('button',{name:'Unverändert erneut senden',exact:true}).click();
    await modal().waitFor({state:'detached'});await ready(page);
    await page.locator('[data-pending-indicator]').waitFor({state:'hidden'});
    const projectWrites=records.filter(r=>r.path==='/api/v1/projects');
    assert.equal(projectWrites.length,3);assert.ok(projectWrites.every(r=>r.body.customer_id===customer.id&&r.body.customer===undefined));
    const [original,retried]=projectWrites.slice(1);
    assert.equal(original.delivery,'aborted_after_server_acceptance');
    assert.match(original.body.request_id,/^[a-f0-9]{32}$/);
    assert.notEqual(projectWrites[0].body.request_id,original.body.request_id);
    assert.equal(retried.rawBody,original.rawBody,'OfficeApi pending retry must preserve exact original request bytes');
    assert.deepEqual(retried.body,original.body);
    assert.equal(retried.status,201);assert.deepEqual(retried.value,original.value);
    assert.ok(projectReads.length>readsBeforeRetry,'pending completion must reload actual projects');
    const afterRetry=customerProjects(projectReads.at(-1));
    assert.equal(afterRetry.length,2);
    assert.deepEqual(afterRetry.map(item=>item.id).sort(),beforeRetry.map(item=>item.id).sort());
    assert.equal(afterRetry.filter(item=>item.id===original.value.id).length,1);
    retryEvidence={customer_id:customer.id,request_id:original.body.request_id,accepted_project_id:original.value.id,
      retry_project_id:retried.value.id,before_retry:beforeRetry,after_retry:afterRetry,
      retry_via:'Unbestätigte Antworten → Unverändert erneut senden → OfficeApi.retry',exact_request_bytes:true};
    await page.screenshot({path:path.join(screenshots,'project-create-retry-confirmed.png'),fullPage:true,animations:'disabled'});
    await navigate(page,'Kontakte');
    assert.equal(await page.locator('.list-row').filter({hasText:'Projektfluss Kundin'}).count(),1);
    assert.ok(records.every(r=>r.status>=200&&r.status<300));
    console.log('Actual contact forms → existing customer project → offer → order → invoice draft: stable customer/project, full billing address and exact 119.00 EUR passed. Invoice not issued by SQLite.');
    console.log('Lost actual POST /projects 201 after server acceptance → OfficeApi pending retry: identical bytes/request ID/result ID; same customer and two projects before and after retry passed.');
  } finally {
    await context.unroute(pattern);
    await fs.writeFile(path.join(screenshots,'project-customer-http.json'),JSON.stringify(records,null,2));
    await fs.writeFile(path.join(screenshots,'project-customer-retry.json'),JSON.stringify({projectReads,capabilityReads,retryEvidence},null,2));
  }
}
module.exports={projectCustomerFlow};
