"""PostgreSQL storage for the shared domain rules; SQLite stays local-only."""
import threading

import psycopg
from psycopg.rows import dict_row

from core import Office

SCHEMA_VERSION = 1
# Serialize mutations across processes as well as threads in this small pilot.
LOCK_ID = 741290518


class Row(dict):
    def __getitem__(self, key):
        return tuple(self.values())[key] if isinstance(key, int) else super().__getitem__(key)


def row_factory(cursor):
    names = [column.name for column in (cursor.description or [])]
    return lambda values: Row(zip(names, values))


class Database:
    def __init__(self, dsn):
        self.dsn = dsn
        self.contexts = []
        self.connection = self.connect()

    def connect(self):
        connection = psycopg.connect(self.dsn, autocommit=True, row_factory=row_factory, connect_timeout=5)
        try:
            connection.execute("SET statement_timeout = '15s'")
            connection.execute("SET lock_timeout = '10s'")
            connection.execute("SET idle_in_transaction_session_timeout = '30s'")
        except BaseException:
            connection.close()
            raise
        return connection

    def reconnect(self):
        # Never resume a failed transaction on a new connection mid-request.
        if self.connection.closed and not self.contexts:
            self.connection = self.connect()

    def execute(self, query, parameters=()):
        self.reconnect()
        # Shared domain statements contain only positional parameters, no '?' literals.
        return self.connection.execute(query.replace('?', '%s'), parameters)

    def __enter__(self):
        self.reconnect()
        context = self.connection.transaction()
        context.__enter__()
        self.contexts.append(context)
        try:
            if len(self.contexts) == 1:
                self.execute('SELECT pg_advisory_xact_lock(?)', (LOCK_ID,))
        except BaseException as error:
            self.contexts.pop().__exit__(type(error), error, error.__traceback__)
            raise
        return self

    def __exit__(self, kind, value, traceback):
        return self.contexts.pop().__exit__(kind, value, traceback)

    def close(self):
        self.connection.close()


class PostgresOffice(Office):
    integrity_error = psycopg.IntegrityError

    def __init__(self, dsn):
        self.lock = threading.RLock()
        self.db = Database(dsn)
        try:
            row = self.db.execute('SELECT version FROM smartplan_schema').fetchone()
            if not row or row['version'] != SCHEMA_VERSION:
                raise RuntimeError('PostgreSQL-Schema zuerst migrieren; Version nicht unterstützt.')
        except BaseException:
            self.db.close()
            raise
        self.failed_logins = {}


def migrate(dsn):
    """Explicit, transactional schema creation; never performed by an HTTP request."""
    with psycopg.connect(dsn, row_factory=dict_row, connect_timeout=5) as connection:
        connection.execute('SELECT pg_advisory_xact_lock(%s)', (LOCK_ID,))
        connection.execute('CREATE TABLE IF NOT EXISTS smartplan_schema(version INTEGER NOT NULL)')
        row = connection.execute('SELECT version FROM smartplan_schema').fetchone()
        if row:
            if row['version'] != SCHEMA_VERSION:
                raise RuntimeError('Nicht unterstützte PostgreSQL-Schemaversion.')
            return
        connection.execute('''
            CREATE TABLE users(id TEXT PRIMARY KEY, email TEXT UNIQUE NOT NULL, salt TEXT NOT NULL,
              password TEXT NOT NULL, role TEXT NOT NULL CHECK(role IN ('owner','manager','technician','accountant')),
              active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1)));
            CREATE TABLE sessions(token TEXT PRIMARY KEY,user_id TEXT REFERENCES users(id),expiry DOUBLE PRECISION);
            CREATE TABLE customers(id TEXT PRIMARY KEY,name TEXT NOT NULL,contact TEXT NOT NULL,
              email TEXT NOT NULL,phone TEXT NOT NULL,address TEXT NOT NULL,notes TEXT NOT NULL,
              active INTEGER NOT NULL CHECK(active IN (0,1)),dedupe_key TEXT NOT NULL UNIQUE,
              created_at TEXT NOT NULL,updated_at TEXT NOT NULL);
            CREATE TABLE projects(id TEXT PRIMARY KEY,name TEXT NOT NULL,customer TEXT NOT NULL,
              customer_id TEXT REFERENCES customers(id));
            CREATE INDEX projects_customer ON projects(customer_id);
            CREATE TABLE assignments(user_id TEXT REFERENCES users(id),project_id TEXT REFERENCES projects(id),
              PRIMARY KEY(user_id,project_id));
            CREATE TABLE reports(id TEXT PRIMARY KEY,project_id TEXT REFERENCES projects(id),
              payload TEXT NOT NULL,pdf BYTEA,pdf_hash TEXT,onedrive_id TEXT,
              rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE);
            CREATE INDEX reports_project ON reports(project_id);
            CREATE TABLE audit(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              user_id TEXT,action TEXT,object_id TEXT,at TEXT);
            CREATE TABLE secrets(name TEXT PRIMARY KEY,value TEXT);
            CREATE TABLE mfa(user_id TEXT PRIMARY KEY REFERENCES users(id),secret TEXT NOT NULL,
              last_step BIGINT NOT NULL DEFAULT -1,recovery TEXT NOT NULL);
            CREATE TABLE auth_challenges(token TEXT PRIMARY KEY,user_id TEXT REFERENCES users(id),
              credential TEXT NOT NULL,secret TEXT NOT NULL,expiry DOUBLE PRECISION NOT NULL,
              failures INTEGER NOT NULL DEFAULT 0);
            CREATE TABLE login_limits(key TEXT PRIMARY KEY,failures INTEGER NOT NULL,
              reset_at DOUBLE PRECISION NOT NULL);
            INSERT INTO smartplan_schema VALUES(1);
        ''')
