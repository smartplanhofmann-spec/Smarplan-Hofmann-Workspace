"""Generate actual synthetic v3 commands, source evidence and accepted history.

The active product default is unchanged. No production data, network provider
or bank transfer is used; money facts are synthetic documentary records.
"""
import json
from pathlib import Path
import sys
from unittest.mock import patch

ROOT=Path(__file__).resolve().parents[3]
sys.path.insert(0,str(ROOT/'backend'))

from test_business_travel_v3 import TravelV3WorkflowTests
from test_business_planning import rid
from business_travel_allowances import _ref,validate_integrity
from payroll_travel_rates_2026 import catalog
from travel_allowance_cash import record_payment,public_source


def snapshot():
    fixture=TravelV3WorkflowTests();fixture.setUp()
    try:
        with fixture.v3():
            body,proof=fixture.mixed_body()
            origin=fixture.upload(purpose='expense_receipt',visible=True,actor=fixture.technician,marker=b'Synthetic mixed travel actual separate transport expense')
            expense=fixture.hr.save_expense(fixture.technician,dict(request_id=rid(),employee_id=fixture.employee['id'],revision=0,
                purpose='Synthetic actual mixed transport cost',start_date='2026-10-26',end_date='2026-10-26',
                items=[dict(date='2026-10-26',description='Synthetic actual ticket with separate private share',amount_minor=1000,currency='EUR',receipt_file_id=origin['id'],project_id=fixture.project)]))
            expense=fixture.hr.expense_action(fixture.technician,expense['id'],'submit',dict(request_id=rid(),revision=expense['revision']))
            expense=fixture.hr.expense_action(fixture.owner,expense['id'],'approve',dict(request_id=rid(),revision=expense['revision'],reason='Original cost split independently checked.'))
            body['details'].update(expense_refs=[_ref(expense)],expense_allocations=[dict(expense_ref=_ref(expense),receipt_file_id=origin['id'],kind='transport',business_minor=600,private_minor=400,provided_minor=0,review_note='Direct original cost split differs from overall programme and is separately evidenced.')])
            saved=fixture.api.save_trip(fixture.technician,body)
            submission_body=dict(request_id=rid(),employee_id=fixture.employee['id'],revision=saved['revision'],source_hash=fixture.api._basis(fixture.employee['id']),confirmed=True)
            submitted=fixture.api.trip_action(fixture.technician,saved['target_id'],'submit',submission_body);trip=submitted['result']
            approval_body=fixture.approval(trip,requested_meal_minor=933)
            preview_body={key:value for key,value in approval_body.items() if key not in ('request_id','id','revision','source_hash','preview_hash','confirmed')}
            preview=fixture.api.preview(fixture.owner,preview_body);accepted=fixture.api.approve(fixture.owner,approval_body)
            payment_body=fixture.payment(accepted['result'],1000);paid=record_payment(fixture.api,fixture.owner,payment_body)
            original_json=fixture.api.export(fixture.owner,accepted['target_id'],1,'json')[0]
            correction_body=fixture.approval(trip,requested_meal_minor=800,correction_of=_ref(accepted['result']),review_note='Documented employer reimbursement revised to 8 EUR; original programme and earlier actual payment retained.')
            correction_body.update(id=accepted['target_id'],revision=1)
            corrected=fixture.api.approve(fixture.owner,correction_body)
            if fixture.api.export(fixture.owner,accepted['target_id'],1,'json')[0]!=original_json:raise AssertionError('Original accepted export changed')
            result=dict(provenance='Synthetic actual v3 TravelAllowances/PersonnelWorkflow commands; generated by web/office/tests/travel_v3_fixture.py',
                catalog=catalog(),employee=fixture.employee,sources=fixture.api.sources(fixture.owner,fixture.employee['id']),
                program_proof=proof,expense=expense,trip_body=body,trip_receipt=saved,submission_body=submission_body,submission_receipt=submitted,trip=trip,
                trip_history=fixture.api.get(fixture.owner,'trip',trip['id'],history=True),
                preview_body=preview_body,preview=preview,calculation=accepted['result']['calculation'],approval_body=approval_body,approval_receipt=accepted,settlement=accepted['result'],
                correction_body=correction_body,correction_receipt=corrected,settlement_history=fixture.api.get(fixture.owner,'settlement',accepted['target_id'],history=True),
                payment_body=payment_body,payment_receipt=paid,cash_source=public_source(fixture.office,paid['target_id']))
        with patch('payroll_travel_2026.RULE_VERSION','de_travel_2026_v2'),patch('business_travel_allowances.RULE_VERSION','de_travel_2026_v2'):
            if not validate_integrity(fixture.office):raise AssertionError('Historical v3 integrity under v2 default failed')
        return result
    finally:
        fixture.tearDown();fixture.doCleanups()


if __name__=='__main__':
    target=Path(sys.argv[1]) if len(sys.argv)>1 else ROOT/'app/test/fixtures/travel_allowances_v3.json'
    result=snapshot();target.write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps(dict(target=str(target),rule_version=result['preview']['rule_version'],tax_free_minor=result['preview']['totals']['tax_free_minor'],historical_revisions=len(result['settlement_history']['items']))))
