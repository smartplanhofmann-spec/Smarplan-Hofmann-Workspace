"""Factor values from a separate Java execution of pinned BMF XML expressions.

Frozen expected values are never generated by the Python implementation under
test. See scripts/payroll-factor-reference.py and the dated evidence record.
"""
import hashlib
import json
from pathlib import Path
import unittest

from core import Problem
import payroll_pap_2026 as historical
from payroll_pap_factor_2026 import (calculate_standard_factor_tax,
    FACTOR_PAP_VERSION, FACTOR_PAP_PROVENANCE, FACTOR_PAP_SHA256)


REFERENCE = Path(__file__).with_name('testdata') / 'payroll_factor_2026.json'


def inputs(**changes):
    return dict(dict(gross_minor=500000, period=2, tax_class=4, factor='0.753',
        children_half_units=0, additional_health_percent='2.90', saxony=False,
        childless_surcharge=True, care_child_discounts=0, church_member=False,
        allowance_minor=0, addition_minor=0), **changes)


class FactorPAP2026(unittest.TestCase):
    def test_all_independent_xml_reference_values(self):
        proof = json.loads(REFERENCE.read_text(encoding='utf-8'))
        self.assertEqual(proof['xml_sha256'], FACTOR_PAP_PROVENANCE['reviewed_xml_sha256'])
        self.assertFalse(proof['direct_official_xml_download'])
        self.assertFalse(proof['official_software_approval'])
        self.assertEqual(len(proof['cases']), 170)
        for case in proof['cases']:
            with self.subTest(inputs=case['inputs']):
                self.assertEqual(calculate_standard_factor_tax(**case['inputs']), case['expected'])

    def test_annual_rounding_precedes_monthly_allocation(self):
        # Independent general PAP table: annual LSt = 9389 EUR at 60000 EUR.
        # MBERECH: floor(9389 * .753) = 7069 EUR, then floor(706900 / 12).
        result = calculate_standard_factor_tax(**inputs(church_member=True))
        self.assertEqual(result, dict(LSTLZZ=58908, SOLZLZZ=0, BK=58908))
        plain = historical.calculate_standard_tax(**{k:v for k,v in inputs().items() if k != 'factor'})
        self.assertNotEqual(result['LSTLZZ'], plain['LSTLZZ'] * 753 // 1000)

    def test_solidarity_threshold_uses_factored_child_adjusted_assessment(self):
        # Official general table at 110000 EUR: 27393 EUR; factor -> 20626 EUR.
        # Mitigation: floor((20626 - 20350) * .119 * 100) = 3284 cents.
        result = calculate_standard_factor_tax(**inputs(gross_minor=11000000,
            period=1, church_member=True))
        self.assertEqual(result, dict(LSTLZZ=2062600, SOLZLZZ=3284, BK=2062600))
        child = calculate_standard_factor_tax(**inputs(gross_minor=11000000,
            period=1, children_half_units=2, church_member=True))
        self.assertEqual(child['LSTLZZ'], result['LSTLZZ'])
        self.assertLess(child['BK'], result['BK'])
        self.assertEqual(child['SOLZLZZ'], 0)
        nonmember = calculate_standard_factor_tax(**inputs(gross_minor=11000000,
            period=1, children_half_units=2, church_member=False))
        self.assertEqual(nonmember, dict(child, BK=0))

    def test_zero_is_an_explicit_factor_and_not_a_missing_value(self):
        for factor in ('0.000', '0.001', '0.999'):
            with self.subTest(factor=factor):
                result = calculate_standard_factor_tax(**inputs(factor=factor))
                self.assertGreaterEqual(result['LSTLZZ'], 0)
        self.assertEqual(calculate_standard_factor_tax(**inputs(factor='0.000', church_member=True)),
                         dict(LSTLZZ=0, SOLZLZZ=0, BK=0))

    def test_factor_and_scope_are_explicit_without_silent_rounding(self):
        bad = [{'factor': v} for v in (None, True, 0.753, 753, '', '0.75', '0,753',
            '0.7530', '0.7539', '1.000', '-0.100', '0.７５３', ' 0.753', '0.753\n')]
        bad += [dict(tax_class=v) for v in (1, 2, 3, 5, 6, 4.0, '4', True)]
        bad += [dict(period=v) for v in (0, 3, 4, True, 2.0)]
        bad += [dict(allowance_minor=v) for v in (1, -1, False, '0')]
        bad += [dict(addition_minor=v) for v in (1, -1, False, '0')]
        bad += [dict(gross_minor=v) for v in (-1, 1.0, True, 10**12 // 12 + 1)]
        bad += [dict(church_member=v) for v in (0, 1, None)]
        for change in bad:
            with self.subTest(change=change), self.assertRaises(Problem):
                calculate_standard_factor_tax(**inputs(**change))

    def test_inherited_standard_insurance_and_child_validation(self):
        for change in ({'children_half_units': True}, {'children_half_units': 21},
                {'additional_health_percent': '2.995'}, {'additional_health_percent': 'nan'},
                {'saxony': 0}, {'childless_surcharge': False, 'care_child_discounts': 5},
                {'childless_surcharge': True, 'care_child_discounts': 1}):
            with self.subTest(change=change), self.assertRaises(Problem):
                calculate_standard_factor_tax(**inputs(**change))

    def test_version_and_provenance_distinguish_the_additive_kernel(self):
        self.assertNotEqual(FACTOR_PAP_VERSION, historical.PAP_VERSION)
        self.assertEqual(FACTOR_PAP_PROVENANCE['annual_primitive_sha256'],
            hashlib.sha256(Path(historical.__file__).read_bytes()).hexdigest())
        self.assertFalse(FACTOR_PAP_PROVENANCE['runtime_network'])
        self.assertFalse(FACTOR_PAP_PROVENANCE['official_software_approval'])
        self.assertEqual(len(FACTOR_PAP_SHA256), 64)
        before = (historical.PAP_VERSION, historical.PAP_SHA256,
                  historical.calculate_standard_tax(**{k:v for k,v in inputs().items() if k != 'factor'}))
        calculate_standard_factor_tax(**inputs())
        self.assertEqual(before, (historical.PAP_VERSION, historical.PAP_SHA256,
            historical.calculate_standard_tax(**{k:v for k,v in inputs().items() if k != 'factor'})))


if __name__ == '__main__':
    unittest.main()
